"""Render Python source from a parsed TL schema.

Three modules come out of here:

``types.py``
    2183 :class:`~tdpy.api.base.TDObject` structs plus 211 union aliases, one
    per abstract TL class.
``functions.py``
    1022 request structs, one per TDLib function.
``methods.py``
    1022 typed ``async def`` wrappers, plus the 28 that TDLib allows to run
    synchronously.

Cycles in the schema are unavoidable (``Message`` holds a ``MessageContent``
which holds a ``Message``), so every generated module relies on
``from __future__ import annotations`` and lets msgspec resolve the strings
when a decoder is first built.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
import textwrap
from collections.abc import Iterable

from tdpy.codegen.tl_parser import Definition, Field, Schema

__all__ = [
    "emit_functions",
    "emit_methods",
    "emit_types",
    "format_source",
    "python_type",
    "schema_digest",
    "snake_case",
]

#: TL primitives that map onto Python builtins rather than generated classes.
PRIMITIVES = {
    "double": "float",
    "string": "str",
    "int32": "int",
    "int53": "int",
    "int64": "Int64",
    "bytes": "bytes",
    "Bool": "bool",
}

#: The value a non-nullable primitive field falls back to. TDLib treats an
#: absent scalar as its zero, so these defaults match the server's own reading.
ZERO_DEFAULTS = {
    "float": "0.0",
    "str": '""',
    "int": "0",
    "Int64": "Int64(0)",
    "bytes": 'b""',
    "bool": "False",
}

#: Builtins that appear in annotations. A field with one of these names
#: shadows it for the rest of the class body, which breaks the annotation at
#: runtime -- `chatActiveStories` really does have a field called `list`.
BUILTIN_ANNOTATIONS = frozenset({"list", "str", "int", "float", "bool", "bytes"})

_DOC_WIDTH = 92
_VECTOR = "vector<"

_BANNER = """# @generated by `python -m tdpy.codegen` from td_api.tl -- do not edit.
#
# Schema sha256: {digest}
# Regenerate after updating tools/td_api.tl; `python -m tdpy.codegen --check`
# fails CI when this file and the schema disagree.
"""


def schema_digest(text: str) -> str:
    """Fingerprint the schema so generated code can be checked against it."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def snake_case(name: str) -> str:
    """``sendMessage`` -> ``send_message``."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def python_type(tl_type: str, schema: Schema) -> str:
    """Map a TL type onto the Python type the generated code should use.

    A lowercase name is a concrete constructor and becomes its struct; an
    uppercase name is either an abstract class (a union alias) or a class with
    exactly one constructor, in which case the struct *is* the alias.
    """
    if tl_type in PRIMITIVES:
        return PRIMITIVES[tl_type]
    if tl_type.startswith(_VECTOR):
        return f"list[{python_type(tl_type[len(_VECTOR) : -1], schema)}]"
    if schema.is_abstract(tl_type):
        return tl_type
    return tl_type[0].upper() + tl_type[1:]


def _qualify(rendered: str, shadowed: frozenset[str]) -> str:
    """Point annotations at ``builtins`` when a sibling field shadows the name.

    Splits on identifier boundaries rather than using a regular expression, so
    that a type such as StoryList is never mistaken for the shadowed list.
    """
    if not shadowed:
        return rendered
    pieces: list[str] = []
    token = ""
    for char in rendered:
        if char.isalnum() or char == "_":
            token += char
            continue
        if token:
            pieces.append(f"builtins.{token}" if token in shadowed else token)
            token = ""
        pieces.append(char)
    if token:
        pieces.append(f"builtins.{token}" if token in shadowed else token)
    return "".join(pieces)


def _shadowed(definition: Definition) -> frozenset[str]:
    return frozenset({field.name for field in definition.fields} & BUILTIN_ANNOTATIONS)


def _annotation(field: Field, schema: Schema, shadowed: frozenset[str] = frozenset()) -> str:
    rendered = _qualify(python_type(field.tl_type, schema), shadowed)
    return f"{rendered} | None" if field.nullable else rendered


def _default(field: Field, schema: Schema) -> str | None:
    """The default for a field, or ``None`` if it must be supplied.

    TDLib never marks a primitive optional, so the three cases do not overlap:
    documented-optional gets ``None``, scalars and vectors get their zero, and
    everything else is required.
    """
    if field.nullable:
        return "None"
    rendered = python_type(field.tl_type, schema)
    if rendered in ZERO_DEFAULTS:
        return ZERO_DEFAULTS[rendered]
    if rendered.startswith("list["):
        return "[]"
    return None


def _escape(text: str) -> str:
    """Make arbitrary schema prose safe inside a triple-quoted docstring."""
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _guard(text: str) -> str:
    """Keep prose ending in a quote mark from closing the docstring early.

    TDLib documents the bot-command entity as beginning with a slash wrapped
    in quote marks. Rendered naively, that run of quote marks merges with the
    closing delimiter and the module stops parsing. One space separates them.
    """
    return f"{text} " if text.endswith('"') else text


def _wrap(text: str, indent: str, hanging: str = "") -> list[str]:
    return textwrap.wrap(
        text,
        width=_DOC_WIDTH,
        initial_indent=indent,
        subsequent_indent=indent + hanging,
        break_long_words=False,
        break_on_hyphens=False,
    ) or [f"{indent}{text}"]


def _docstring(
    summary: str,
    fields: Iterable[Field],
    indent: str,
    *,
    section: str,
    returns: str = "",
) -> list[str]:
    """Render a Google-style docstring, or a one-liner when there is nothing else."""
    fields = list(fields)
    body = _wrap(_escape(summary), indent)
    if not fields and not returns:
        if len(body) == 1:
            return [f'{indent}"""{_guard(body[0].strip())}"""']
        return [f'{indent}"""{body[0].strip()}', *body[1:], f'{indent}"""']

    lines = [f'{indent}"""{body[0].strip()}', *body[1:]]
    if fields:
        lines += ["", f"{indent}{section}:"]
        for field in fields:
            doc = _escape(field.doc) or "Undocumented in the TL schema."
            lines += _wrap(f"{field.name}: {doc}", f"{indent}    ", "    ")
    if returns:
        lines += ["", f"{indent}Returns:", *_wrap(returns, f"{indent}    ", "    ")]
    lines.append(f'{indent}"""')
    return lines


def _struct(definition: Definition, schema: Schema, section: str) -> list[str]:
    lines = [
        # kw_only is not inherited from TDObject the way tag_field and
        # omit_defaults are, and without it msgspec rejects any struct whose
        # schema order puts a required field after an optional one.
        f'class {definition.class_name}(TDObject, tag="{definition.name}", kw_only=True):',
        *_docstring(definition.doc, definition.fields, "    ", section=section),
    ]
    if not definition.fields:
        return lines

    lines.append("")
    shadowed = _shadowed(definition)
    for field in definition.fields:
        default = _default(field, schema)
        suffix = f" = {default}" if default is not None else ""
        lines.append(f"    {field.name}: {_annotation(field, schema, shadowed)}{suffix}")
    return lines


def _referenced_types(definitions: Iterable[Definition], schema: Schema) -> list[str]:
    """Names from ``types.py`` that the given definitions mention."""
    names: set[str] = set()
    for definition in definitions:
        for field in definition.fields:
            rendered = python_type(field.tl_type, schema)
            while rendered.startswith("list["):
                rendered = rendered[len("list[") : -1]
            if rendered not in ZERO_DEFAULTS:
                names.add(rendered)
    return sorted(names)


def _builtins_import(definitions: Iterable[Definition]) -> list[str]:
    return ["import builtins", ""] if any(_shadowed(d) for d in definitions) else []


def emit_types(schema: Schema, digest: str) -> str:
    """Render the struct and union-alias module."""
    lines = [
        _BANNER.format(digest=digest),
        '"""Every TDLib data type, generated from ``td_api.tl``."""',
        "",
        "from __future__ import annotations",
        "",
        *_builtins_import(schema.constructors),
        "from tdpy.api.base import Int64, TDObject",
        "",
        "",
    ]
    for definition in schema.constructors:
        lines += _struct(definition, schema, "Attributes")
        lines += ["", ""]

    members = schema.members
    by_name = {d.name: d for d in schema.constructors}
    lines += ["# Abstract TL classes. msgspec picks the member by its ``@type`` tag.", ""]
    for name, doc in schema.classes.items():
        implementations = [by_name[member].class_name for member in members[name]]
        lines.append(f"#: {doc}" if doc else f"#: One of {len(implementations)} variants.")
        lines.append(f"{name} = (")
        lines += [
            f"    {implementation}" if index == 0 else f"    | {implementation}"
            for index, implementation in enumerate(implementations)
        ]
        lines += [")", ""]
    return "\n".join(lines) + "\n"


def emit_functions(schema: Schema, digest: str) -> str:
    """Render the request-struct module."""
    imports = _referenced_types(schema.functions, schema)
    lines = [
        _BANNER.format(digest=digest),
        '"""Every TDLib function as a request object, generated from ``td_api.tl``."""',
        "",
        "from __future__ import annotations",
        "",
        *_builtins_import(schema.functions),
        "from tdpy.api.base import Int64, TDObject",
    ]
    if imports:
        lines += ["from tdpy.api.types import (", *(f"    {name}," for name in imports), ")"]
    lines += ["", ""]

    for definition in schema.functions:
        lines += _struct(definition, schema, "Args")
        lines += ["", ""]
    return "\n".join(lines) + "\n"


def _method(definition: Definition, schema: Schema, *, synchronous: bool) -> list[str]:
    name = snake_case(definition.name)
    result = python_type(definition.result, schema)
    keyword = "def" if synchronous else "async def"
    call = "self._execute" if synchronous else "await self._call"

    signature = [f"    {keyword} {name}("]
    arguments: list[str] = []
    if definition.fields:
        signature += ["        self,", "        *,"]
        for field in definition.fields:
            annotation = _annotation(field, schema)
            default = _default(field, schema)
            if default == "[]":
                # A shared mutable default is a genuine bug in a plain function
                # signature, unlike in a struct where msgspec copies it per call.
                annotation = f"{annotation} | None"
                default = "None"
                arguments.append(f"            {field.name}={field.name} or [],")
            else:
                arguments.append(f"            {field.name}={field.name},")
            suffix = f" = {default}" if default is not None else ""
            signature.append(f"        {field.name}: {annotation}{suffix},")
    else:
        signature.append("        self,")
    signature.append(f"    ) -> {result}:")

    # Four TDLib functions take a parameter called `result`; the local that
    # holds the reply has to step aside rather than shadow it.
    local = "result"
    while any(field.name == local for field in definition.fields):
        local = f"_{local}"

    returns = f"{result}: {_escape(definition.doc)}"
    body = [
        f"        request = functions.{definition.class_name}(",
        *arguments,
        "        )",
        # The local annotation is what keeps mypy --strict happy: _call cannot
        # type its own result, and returning Any straight out of a typed
        # function trips warn_return_any.
        f"        {local}: {result} = {call}(request, {result})",
        f"        return {local}",
    ]
    return [
        *signature,
        *_docstring(definition.doc, definition.fields, "        ", section="Args", returns=returns),
        *body,
    ]


def emit_methods(schema: Schema, digest: str) -> str:
    """Render the typed method mixins."""
    synchronous = [d for d in schema.functions if d.is_synchronous]
    results = {python_type(d.result, schema) for d in schema.functions}
    imports = sorted(
        (results | set(_referenced_types(schema.functions, schema))) - set(ZERO_DEFAULTS)
    )
    lines = [
        _BANNER.format(digest=digest),
        '"""Typed wrappers for every TDLib function, generated from ``td_api.tl``."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "from tdpy.api import functions",
        "from tdpy.api.base import Int64, TDObject",
        "from tdpy.api.types import (",
        *(f"    {name}," for name in imports),
        ")",
        "",
        "",
        "class Methods:",
        '    """Every TDLib function, as a typed coroutine.',
        "",
        "    Mixed into the typed client, which supplies :meth:`_call`.",
        '    """',
        "",
        "    async def _call(self, request: TDObject, result: Any) -> Any:",
        '        """Send ``request`` and decode the reply as ``result``."""',
        "        raise NotImplementedError",
        "",
    ]
    for definition in schema.functions:
        lines += _method(definition, schema, synchronous=False)
        lines.append("")

    lines += [
        "",
        "class SyncMethods:",
        f'    """The {len(synchronous)} functions TDLib can run without a request queue.',
        "",
        "    These need no client and no event loop, so they work before start-up.",
        '    """',
        "",
        "    def _execute(self, request: TDObject, result: Any) -> Any:",
        '        """Run ``request`` in the calling thread and decode it as ``result``."""',
        "        raise NotImplementedError",
        "",
    ]
    for definition in synchronous:
        lines += _method(definition, schema, synchronous=True)
        lines.append("")
    return "\n".join(lines) + "\n"


def _ruff(arguments: list[str], source: str) -> str:
    """Pipe ``source`` through ruff, returning it unchanged if ruff is unusable."""
    try:
        completed = subprocess.run(
            ["ruff", *arguments, "--stdin-filename", "generated.py", "-"],
            input=source,
            capture_output=True,
            text=True,
            # Windows defaults stdin to the ANSI code page under text=True, and
            # TDLib's prose is not ASCII. Swallowing that once hid a real bug.
            encoding="utf-8",
            check=True,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"warning: ruff {arguments[0]} failed, emitting as-is: {exc}", file=sys.stderr)
        return source
    return completed.stdout


def format_source(source: str) -> str:
    """Sort imports and format generated code exactly as the repo's ruff would.

    Delegating to ruff rather than reimplementing its ordering is what keeps
    ``--check`` from failing over a sorting rule the generator does not know
    about.
    """
    return _ruff(["format"], _ruff(["check", "--select", "I", "--fix", "--quiet"], source))
